#!/usr/bin/env python3
"""Generate one Verso chapter per world of a lean4game game from its game data.

Usage: python3 scripts/gen_worlds.py [--force] [--lang=en]

Writes `NNGSite/Worlds/<World>.lean` (existing files are kept unless `--force` is given, so they
can be edited by hand afterwards) and `NNGSite/Worlds.lean`, which lists the worlds in an order
compatible with the dependency graph.
"""
import json
import re
import sys
from pathlib import Path

site = Path(__file__).resolve().parent.parent
gamedata = site.parent / 'nng4' / '.lake' / 'gamedata'
out = site / 'NNGSite' / 'Worlds'
force = '--force' in sys.argv
lang = next((a.split('=', 1)[1] for a in sys.argv if a.startswith('--lang=')), 'en')

game = json.loads((gamedata / 'game.json').read_text())
nodes = game['worlds']['nodes']
edges = game['worlds']['edges']

# Order worlds by depth in the dependency graph, keeping the game's order within a depth.
preds = {w: [a for a, b in edges if b == w] for w in nodes}
depth = {}
def get_depth(w):
    if w not in depth:
        depth[w] = 1 + max((get_depth(p) for p in preds[w]), default=-1)
    return depth[w]
order = sorted(nodes, key=lambda w: (get_depth(w), list(nodes).index(w)))


catalogue_file = site.parent / 'nng4' / '.i18n' / lang / 'Game.json'
catalogue = json.loads(catalogue_file.read_text()) if lang != 'en' and catalogue_file.exists() else {}
block = re.compile(r'((?<!\\)(`+|\${1,2})([\s\S]*?)\2)')


def translate(s):
    """Same lookup as NNGSite.translate (code spans and math become placeholders §n)."""
    blocks = []
    def placeholder(m):
        blocks.append(m.group(0))
        return f'§{len(blocks) - 1}'
    key = block.sub(placeholder, s)
    for k in (key.replace('\\', '\\\\'), key, s):
        if catalogue.get(k):
            return re.sub(r'(?<!\\)§(\d+)', lambda m: blocks[int(m.group(1))], catalogue[k])
    return s


def title(t):
    # Identifiers such as `add_comm` would be read as emphasis by Verso.
    return ' '.join(f'`{w}`' if '_' in w else w for w in t.split(' '))


out.mkdir(parents=True, exist_ok=True)
for w in order:
    path = out / f'{w}.lean'
    if path.exists() and not force:
        continue
    lines = [
        'import VersoManual',
        'import NNGSite.Level',
        '',
        'open Verso.Genre Manual',
        'open NNGSite',
        '',
        f'#doc (Manual) "{translate(nodes[w]["title"])}" =>',
        '',
        # all levels of a world on one page, where level.js shows them one at a time
        '%%%',
        'htmlSplit := .never',
        '%%%',
        '',
        f':::worldIntro "{w}"',
        ':::',
    ]
    for i in range(1, game['worldSize'][w] + 1):
        level = json.loads((gamedata / f'level__{w}__{i}.json').read_text())
        lines += ['', f'# Level {i}: {title(translate(level["title"]))}', '', f':::level "{w}" {i}', ':::']
    path.write_text('\n'.join(lines) + '\n')
    print('wrote', path.relative_to(site))

index = ['-- Generated by scripts/gen_worlds.py.'] + [f'import NNGSite.Worlds.{w}' for w in order]
(site / 'NNGSite' / 'Worlds.lean').write_text('\n'.join(index) + '\n')
print('include in NNGSite.lean:')
for w in order:
    print(f'{{include 1 NNGSite.Worlds.{w}}}')
